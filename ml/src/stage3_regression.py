"""Sydney passing-level continuous-score baselines; research only.

One record is one passing (not a frame); cow-disjoint splits are fixed upstream.
The average of 10 observer scores is an exploratory 0–3 target, not a diagnosis.
Video feature extraction is disabled until target localization and masking are validated.
Test predictions are only generated by an explicit --split test command.
Requires a pre-audited safe-interval manifest and local pretrained weights.
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
import math
import random
from pathlib import Path


def read_manifest(path):
    required={'passing_id','cow_id','split','score','presentation','start_s','end_s','video_path'}
    with Path(path).open(newline='', encoding='utf-8-sig') as f:
        reader=csv.DictReader(f)
        if required - set(reader.fieldnames or ()):
            raise ValueError('missing required columns: ' + ', '.join(sorted(required - set(reader.fieldnames or ()))))
        result=[]
        for n,r in enumerate(reader,2):
            if any(not str(r.get(k,'')).strip() for k in required): raise ValueError(f'row {n} missing required values')
            try:
                r.update(score=float(r['score']), start_s=float(r['start_s']), end_s=float(r['end_s']))
            except ValueError as e: raise ValueError(f'invalid numeric field at row {n}') from e
            if r['split'] not in ('train','validation','test') or not 0<=r['score']<=3 or not (math.isfinite(r['start_s']) and math.isfinite(r['end_s']) and 0<=r['start_s']<r['end_s']):
                raise ValueError(f'invalid split/score/interval at row {n}')
            result.append(r)
    if not result: raise ValueError('empty manifest')
    if len({r['passing_id'] for r in result})!=len(result): raise ValueError('duplicate passing IDs')
    if len({r['presentation'] for r in result})!=len(result): raise ValueError('duplicate presentation IDs')
    groups={}
    for r in result:
        key=r['cow_id']; prior=groups.setdefault(key,r['split'])
        if prior!=r['split']: raise ValueError('cow occurs across splits')
    return result


def regression_metrics(y, pred):
    y,pred=list(y),list(pred)
    if not y or len(y)!=len(pred) or not all(math.isfinite(float(v)) for v in y+pred): raise ValueError('equal non-empty finite predictions required')
    errors=[p-t for t,p in zip(y,pred)]
    mse=sum(v*v for v in errors)/len(errors)
    ymean=sum(y)/len(y); denom=sum((v-ymean)**2 for v in y)
    xmean=sum(pred)/len(pred); xvar=sum((v-xmean)**2 for v in pred)
    cov=sum((a-ymean)*(b-xmean) for a,b in zip(y,pred))
    return {'n':len(y),'mae':sum(abs(e) for e in errors)/len(errors),'rmse':math.sqrt(mse),
            'r2':1-sum(e*e for e in errors)/denom if denom else None,
            'pearson_r':cov/math.sqrt(denom*xvar) if denom and xvar else None}


def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for part in iter(lambda:f.read(1024*1024),b''): h.update(part)
    return h.hexdigest()


def write_predictions(out, rows, predictions, model):
    out=Path(out)
    out.parent.mkdir(parents=True,exist_ok=True)
    if out.exists(): raise FileExistsError(f'refusing to overwrite {out}')
    if len(rows)!=len(predictions): raise ValueError('prediction count mismatch')
    predictions=[float(p) for p in predictions]
    if any(not math.isfinite(p) for p in predictions): raise ValueError('non-finite prediction')
    fields=['passing_id','cow_id','split','y_true','prediction','model']
    with out.open('x',newline='',encoding='utf-8') as f:
        w=csv.DictWriter(f,fieldnames=fields); w.writeheader()
        for r,p in zip(rows,predictions): w.writerow(dict(passing_id=r['passing_id'],cow_id=r['cow_id'],split=r['split'],y_true=r['score'],prediction=p,model=model))
    return regression_metrics([r['score'] for r in rows],predictions)


def require_video_review(row):
    """Explicit evidence gate; metadata approval never substitutes for actual review."""
    for key in ('target_localization_review', 'walking_visibility_review'):
        if str(row.get(key, '')).strip().lower() != 'approved':
            raise ValueError(f"passing {row.get('passing_id', '?')} requires {key}=approved before video analysis")


def image_frames(row, count):
    """Fail closed: metadata approval alone cannot isolate a moving target cow."""
    require_video_review(row)
    raise RuntimeError(
        "Video feature extraction disabled: frame-level target localization "
        "and masking have not been implemented and validated."
    )


def handcrafted(frames):
    """Global brightness/color and frame change summaries; not gait biomarkers."""
    import numpy as np
    arr=frames[:,77:147,:,:].astype(np.float32)/255.
    means=arr.mean(axis=(0,1,2)); stds=arr.std(axis=(0,1,2))
    changes=np.abs(np.diff(arr,axis=0)) if len(arr)>1 else np.zeros_like(arr[:1])
    return np.concatenate([means,stds,[changes.mean(),changes.std()]]).astype(np.float32)


def load_features(rows, count, mode, *, weights=None, device='cpu'):
    import numpy as np
    encoder=transform=None
    if mode=='resnet18':
        import torch
        from torchvision.models import resnet18
        from torchvision.transforms import Normalize
        encoder=resnet18(weights=None)
        encoder.load_state_dict(torch.load(weights, map_location='cpu',weights_only=True))
        encoder.fc=torch.nn.Identity(); encoder.eval().to(device)
        transform=Normalize(mean=[0.485,0.456,0.406],std=[0.229,0.224,0.225])
    features=[]
    for idx,row in enumerate(rows):
        frames=image_frames(row,count)
        if mode=='handcrafted': value=handcrafted(frames)
        else:
            tensor=torch.from_numpy(frames).permute(0,3,1,2).float()/255.
            tensor=transform(tensor).to(device)
            with torch.no_grad(): value=encoder(tensor).mean(0).cpu().numpy()
        features.append(value)
        print(f'{mode}: {idx+1}/{len(rows)} passings',flush=True)
    return np.stack(features)


def training_mean(rows):
    y=[r['score'] for r in rows if r['split']=='train']
    if not y: raise ValueError('no train rows')
    return sum(y)/len(y)


def fit_linear(x,y, xval,yval, *, seed, epochs, patience, learning_rate):
    import numpy as np
    import torch
    torch.manual_seed(seed); random.seed(seed)
    x=np.asarray(x,dtype=np.float32); xval=np.asarray(xval,dtype=np.float32)
    mu=x.mean(0); sd=x.std(0); sd[sd<1e-6]=1.
    xt=torch.from_numpy((x-mu)/sd); xv=torch.from_numpy((xval-mu)/sd)
    yt=torch.tensor(y,dtype=torch.float32).reshape(-1,1); yv=torch.tensor(yval,dtype=torch.float32).reshape(-1,1)
    model=torch.nn.Linear(x.shape[1],1); optimizer=torch.optim.Adam(model.parameters(),lr=learning_rate,weight_decay=1e-4)
    best=float('inf'); best_epoch=0; stale=0; best_state=None
    for epoch in range(1,epochs+1):
        model.train();optimizer.zero_grad();loss=torch.nn.functional.mse_loss(model(xt),yt);loss.backward();optimizer.step()
        model.eval()
        with torch.no_grad(): vl=float(torch.nn.functional.mse_loss(model(xv),yv))
        if vl<best-1e-8:
            best=vl;best_epoch=epoch;stale=0;best_state={k:v.detach().clone() for k,v in model.state_dict().items()}
        else:
            stale+=1
            if stale>=patience:break
    model.load_state_dict(best_state)
    return {'state_dict':model.state_dict(),'mean':torch.tensor(mu),'std':torch.tensor(sd), 'best_epoch':best_epoch,'validation_mse':best}


def eval_linear(model, features):
    import torch
    x=torch.as_tensor(features,dtype=torch.float32)
    sd=model['std']; mu=model['mean']; state=model['state_dict']
    with torch.no_grad(): return (((x-mu)/sd)@state['weight'].T+state['bias']).clamp(0, 3).flatten().tolist()


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('command',choices=['mean','fit','predict','smoke','smoke-synthetic'])
    p.add_argument('--manifest',type=Path);p.add_argument('--output',type=Path,required=True)
    p.add_argument('--weights',type=Path);p.add_argument('--checkpoint',type=Path)
    p.add_argument('--model',choices=['resnet18','handcrafted'],default='resnet18')
    p.add_argument('--split',choices=['validation','test'],default='validation')
    p.add_argument('--seed',type=int,default=42);p.add_argument('--frames',type=int,default=8)
    p.add_argument('--epochs',type=int,default=1000);p.add_argument('--patience',type=int,default=50);p.add_argument('--lr',type=float,default=.001)
    p.add_argument('--device',choices=['cpu','mps','cuda'],default='cpu')
    args=p.parse_args()
    if args.frames<2 or args.epochs<1 or args.patience<1 or args.lr<=0: p.error('frames >= 2 and positive training parameters required')
    if args.command == 'smoke-synthetic':
        import numpy as np
        import torch
        if args.output.exists(): raise FileExistsError(f'output already exists: {args.output}')
        args.output.mkdir(parents=True)
        rng=np.random.default_rng(args.seed)
        feat=rng.normal(size=(4,16)).astype(np.float32)
        truth=[0.3, 0.9, 1.9, 2.7]
        fitted=fit_linear(feat,truth,feat,truth,seed=args.seed,epochs=args.epochs,patience=args.patience,learning_rate=args.lr)
        metrics=regression_metrics(truth,eval_linear(fitted,feat));metrics['smoke_target_rmse']=.10
        metrics['passed']=metrics['rmse']<.10
        metrics['scope']='synthetic training-head wiring only; no video, ResNet, or generalization validation'
        (args.output/'smoke_metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
        print(json.dumps(metrics,indent=2))
        if not metrics['passed']: raise SystemExit('synthetic smoke did not overfit')
        return
    if args.manifest is None: p.error('--manifest is required')
    rows=read_manifest(args.manifest)
    train=[r for r in rows if r['split']=='train']; val=[r for r in rows if r['split']=='validation']
    target=[r for r in rows if r['split']==args.split]
    if not train or not val or not target: raise ValueError('train, validation and requested target split must not be empty')
    if args.output.exists(): raise FileExistsError(f'output already exists: {args.output}')
    if args.command=='mean':
        args.output.mkdir(parents=True)
        mean = training_mean(rows)
        metrics=write_predictions(args.output/f'{args.split}_predictions.csv',target,[mean]*len(target),'training_mean')
        (args.output/'metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
        config = {'model': 'training_mean', 'training_passing_count': len(train),
                  'training_cow_count': len({r['cow_id'] for r in train}),
                  'prediction_split': args.split, 'prediction_cow_count': len({r['cow_id'] for r in target}),
                  'training_mean': mean, 'manifest_sha256': digest(args.manifest),
                  'target': 'mean of ten observer scores per passing, exploratory range 0-3',
                  'note': 'Score-only baseline; no video used. Not a diagnosis.'}
        (args.output/'config.json').write_text(json.dumps(config,indent=2)+'\n')
        print(json.dumps(metrics,indent=2));return
    review_rows = (train + val if args.command == 'fit' else train[:4] if args.command == 'smoke' else target)
    for row in review_rows: require_video_review(row)
    if args.model=='resnet18' and (args.weights is None or not args.weights.is_file()): p.error('resnet18 needs existing --weights file')
    import torch
    args.output.mkdir(parents=True)
    if args.command in ('fit','smoke'):
        selected=train if args.command=='fit' else train[:4]
        feat=load_features(selected,args.frames,args.model,weights=args.weights,device=args.device)
        yf=[r['score'] for r in selected]
        if args.command=='smoke':
            xval,yval=feat,yf
        else:
            xval=load_features(val,args.frames,args.model,weights=args.weights,device=args.device); yval=[r['score'] for r in val]
        fitted=fit_linear(feat,yf,xval,yval,seed=args.seed,epochs=args.epochs,patience=args.patience,learning_rate=args.lr)
        ckpt={'format_version':1,'model':args.model,'seed':args.seed,'frames':args.frames,'weights_sha256':digest(args.weights) if args.weights else None,
              'manifest_sha256':digest(args.manifest),'preprocessing':'crop top 640; mask top-right [1780:2048,0:160]; resize 224x70; pad to 224; ImageNet normalization for ResNet18',**fitted}
        torch.save(ckpt,args.output/'best.pt')
        if args.command=='smoke':
            metrics=regression_metrics(yf,eval_linear(fitted,feat));metrics['smoke_target_rmse']=.10
            metrics['passed']=metrics['rmse']<.10
            (args.output/'smoke_metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
            print(json.dumps(metrics,indent=2));
            if not metrics['passed']: raise SystemExit('smoke did not overfit; do not treat this as generalization performance')
        else:
            metrics=write_predictions(args.output/'validation_predictions.csv',val,eval_linear(fitted,xval),args.model)
            config={'model':args.model,'seed':args.seed,'frames':args.frames,'epochs':args.epochs,'patience':args.patience,'learning_rate':args.lr,'best_epoch':fitted['best_epoch'], 'validation_metrics':metrics,'manifest_sha256':digest(args.manifest),'device':args.device,'torch_version':torch.__version__,'warning':'experimental regression, not a diagnosis; do not tune on test'}
            (args.output/'config.json').write_text(json.dumps(config,indent=2)+'\n');print(json.dumps(config,indent=2))
    else:
        if args.checkpoint is None or not args.checkpoint.is_file(): p.error('predict needs --checkpoint')
        ckpt=torch.load(args.checkpoint,map_location='cpu',weights_only=True)
        if ckpt['model']!=args.model or ckpt['frames']!=args.frames or ckpt['manifest_sha256']!=digest(args.manifest): raise ValueError('checkpoint model/frames/manifest mismatch')
        if ckpt['weights_sha256']!=(digest(args.weights) if args.weights else None): raise ValueError('checkpoint weights mismatch')
        feats=load_features(target,args.frames,args.model,weights=args.weights,device=args.device)
        metrics=write_predictions(args.output/f'{args.split}_predictions.csv',target,eval_linear(ckpt,feats),args.model)
        (args.output/'metrics.json').write_text(json.dumps(metrics,indent=2)+'\n');print(json.dumps(metrics,indent=2))


if __name__=='__main__': main()
