"""Generate the Supabase baseline from the reviewed standalone schema.
Run only before initial deployment. Never rewrite a migration already applied remotely.
Provider-specific Auth/Storage policies are maintained separately in migration 003.
"""
from pathlib import Path
import sys
import re

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT/'supabase/migrations'
BASE = ROOT/'database'

def artifacts():
    core = (BASE/'migrations/001_core.sql').read_text(encoding='utf-8')
    core = core.replace('CREATE EXTENSION IF NOT EXISTS postgis;',
        """CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;
DO $$ BEGIN
 IF (SELECT n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace
     WHERE e.extname='postgis') <> 'extensions' THEN
   RAISE EXCEPTION 'PostGIS must be in extensions; do not relocate/drop an existing populated extension automatically';
 END IF;
END $$;""")
    core = core.replace('CREATE EXTENSION IF NOT EXISTS btree_gist;',
                        'CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;')
    core = core.replace('cattle, public','cattle, extensions, public')
    core = core.replace('-- subject is the verified external auth issuer+subject; never a password.',
                        '-- Supabase Auth owns credentials; deleting a user requires deliberate membership cleanup.')
    core = core.replace('issuer text NOT NULL, subject text NOT NULL,',
                        'user_id uuid NOT NULL REFERENCES auth.users(id),')
    core = core.replace('PRIMARY KEY (org_id,issuer,subject)','PRIMARY KEY (org_id,user_id)')
    core = core.replace('COMMIT;', '''REVOKE ALL ON SCHEMA cattle FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA cattle FROM PUBLIC, anon, authenticated;
COMMIT;''')
    policy = (BASE/'migrations/002_policy_views.sql').read_text(encoding='utf-8')
    policy = 'BEGIN;\nSET LOCAL search_path=cattle,extensions,public;\n\n' + policy[policy.index('CREATE FUNCTION immutable_history()'):policy.index('GRANT SELECT ON ALL TABLES')]
    policy = policy.replace('search_path=cattle,public','search_path=cattle,extensions,public')
    policy = policy.replace("coalesce(nullif(current_setting('app.actor',true),''),session_user)",
                            "coalesce(auth.uid()::text,session_user)")
    policy += 'REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA cattle FROM PUBLIC, anon, authenticated;\nCOMMIT;\n'
    fixture = (BASE/'tests/fixture.sql').read_text(encoding='utf-8')
    fixture = fixture.replace('search_path=cattle,public','search_path=cattle,extensions,public')
    fixture = fixture.replace("INSERT INTO organization(id,name)", """INSERT INTO auth.users(id,email,aud,role) VALUES
 (pg_temp.uid(901),'reviewer@example.invalid','authenticated','authenticated'),
 (pg_temp.uid(902),'other@example.invalid','authenticated','authenticated'),
 (pg_temp.uid(903),'nonmember@example.invalid','authenticated','authenticated');
INSERT INTO organization(id,name)""",1)
    fixture = fixture.replace("INSERT INTO ranch VALUES(pg_temp.uid(2)",
        "INSERT INTO membership VALUES(pg_temp.uid(2),pg_temp.uid(902),'viewer');\nINSERT INTO ranch VALUES(pg_temp.uid(2)",1)
    fixture = fixture.replace("INSERT INTO membership VALUES(pg_temp.uid(1),'https://auth.example.invalid','test-reviewer','reviewer');",
        "INSERT INTO membership VALUES(pg_temp.uid(1),pg_temp.uid(901),'reviewer');")
    fixture = fixture.replace("'org1/flight1/clip1/200.jpg'", "pg_temp.uid(1)::text||'/flight1/clip1/200.jpg'")
    fixture = fixture.replace("'org1/flight1/clip1/0.jpg'", "pg_temp.uid(1)::text||'/flight1/clip1/0.jpg'")
    header = '-- Generated by database/tools/build_supabase.py; see supabase/README.md.\n'
    assertions = (BASE/'tests/supabase_assertions.sql').read_text(encoding='utf-8')
    queries = (BASE/'queries/website.sql').read_text(encoding='utf-8').replace('search_path=cattle,public','search_path=cattle,extensions,public')
    smoke = (BASE/'tests/supabase_query_smoke.sql').read_text(encoding='utf-8')
    assertions = assertions.replace('SET LOCAL ROLE authenticated;', 'SET LOCAL ROLE cattle_backend_user;')
    smoke = smoke.replace('SET LOCAL ROLE authenticated;', 'SET LOCAL ROLE cattle_backend_user;')
    assertions = assertions.replace('ROLLBACK;',smoke+'\nROLLBACK;')
    combined = fixture.replace('COMMIT;','') + '\n' + queries + '\n' + assertions
    combined = re.sub(r'CREATE OR REPLACE FUNCTION pg_temp\.uid.*?\$\$;', '',combined,flags=re.S)
    combined = re.sub(r'pg_temp\.uid\(([^)]+)\)',
        r"('00000000-0000-0000-0000-'||lpad((\1)::text,12,'0'))::uuid",combined)
    return {
        DEST/'20261114193116_core.sql': header+core,
        DEST/'20261114193129_history_views.sql': header+policy,
        ROOT/'supabase/fixtures/synthetic.sql': header+fixture,
        ROOT/'supabase/tests/integration.sql': header+combined,
    }

if __name__ == '__main__':
    for path, content in artifacts().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='utf-8') == content, f'generated artifact drift: {path}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content,encoding='utf-8')
    print('Supabase generated baseline '+('matches source.' if '--check' in sys.argv else 'written.'))
